package index.benchmarks;

import java.util.concurrent.TimeUnit;

import index.sql.SqlBenchHelper;
import org.genfork.grid.sql.SqlEngine;
import org.genfork.grid.threading.ThreadService;
import org.openjdk.jmh.annotations.Benchmark;
import org.openjdk.jmh.annotations.BenchmarkMode;
import org.openjdk.jmh.annotations.Fork;
import org.openjdk.jmh.annotations.Level;
import org.openjdk.jmh.annotations.Measurement;
import org.openjdk.jmh.annotations.Mode;
import org.openjdk.jmh.annotations.OutputTimeUnit;
import org.openjdk.jmh.annotations.Scope;
import org.openjdk.jmh.annotations.Setup;
import org.openjdk.jmh.annotations.State;
import org.openjdk.jmh.annotations.TearDown;
import org.openjdk.jmh.annotations.Threads;
import org.openjdk.jmh.annotations.Warmup;
import org.openjdk.jmh.infra.Blackhole;
import org.slf4j.LoggerFactory;

/**
 * SELECT non-prefix AND on composite UNIQUE vs owner-only prefix and full UNIQUE EQ.
 * <p>
 * Non-prefix AND must stay on the same order as owner-only (prefix seek + cheap residual),
 * not degrade to PK full-scan latency.
 *
 * @author: GenCloud
 * @date: 2026/10
 * @since: 1.2
 */
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.MICROSECONDS)
@Warmup(iterations = 1, time = 1)
@Measurement(iterations = 3, time = 1)
@Fork(1)
@Threads(1)
@State(Scope.Benchmark)
public class SqlCompositeNonPrefixAndBenchmark extends AbstractLatencyBenchmark {
	private static final int SHARDS = 4;
	private static final int ROWS_PER_OWNER = 64;
	private static final int OWNER_ID = 194;
	private static final int CLASS_INDEX = 0;
	private static final String TABLE = "nonprefix_and_bench";

	private SqlEngine engine;
	private String nonPrefixAndSql;
	private String ownerOnlySql;
	private String fullUniqueEqSql;

	@Setup(Level.Trial)
	public void setupBenchmark() {
		// VisibilityDiag DEBUG floods JMH forks (map.get per probe); mute for stamp validity.
		final ch.qos.logback.classic.Logger diag =
				(ch.qos.logback.classic.Logger) LoggerFactory.getLogger("org.genfork.grid.diag");
		diag.setLevel(ch.qos.logback.classic.Level.WARN);
		engine = SqlBenchHelper.createEngine(SHARDS);
		engine.execute(
				"CREATE TABLE " + TABLE + " ("
						+ "id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY, "
						+ "owner_id INT NOT NULL, "
						+ "client_id INT NOT NULL, "
						+ "class_index INT NOT NULL, "
						+ "slot INT NOT NULL, "
						+ "PRIMARY KEY (id, owner_id, client_id))");
		engine.execute(
				"CREATE UNIQUE INDEX uq_nonprefix_and_bench ON " + TABLE
						+ " (owner_id, client_id, class_index)");
		for (int clientId = 1; clientId <= ROWS_PER_OWNER; clientId++) {
			final int classIndex = clientId % 2;
			engine.execute(
					"INSERT INTO " + TABLE + " (owner_id, client_id, class_index, slot) VALUES ("
							+ OWNER_ID + ", " + clientId + ", " + classIndex + ", " + clientId + ")");
		}
		nonPrefixAndSql = "SELECT id FROM " + TABLE
				+ " WHERE owner_id = " + OWNER_ID + " AND class_index = " + CLASS_INDEX;
		ownerOnlySql = "SELECT id FROM " + TABLE + " WHERE owner_id = " + OWNER_ID;
		fullUniqueEqSql = "SELECT id FROM " + TABLE
				+ " WHERE owner_id = " + OWNER_ID + " AND client_id = 2 AND class_index = 0";
	}

	@TearDown(Level.Trial)
	public void tearDownBenchmark() {
		SqlBenchHelper.closeAllStores(engine);
		ThreadService.shutdownNow();
	}

	@Benchmark
	public void selectNonPrefixAnd(Blackhole bh) {
		bh.consume(engine.execute(nonPrefixAndSql).rows().size());
	}

	@Benchmark
	public void selectOwnerOnlyPrefix(Blackhole bh) {
		bh.consume(engine.execute(ownerOnlySql).rows().size());
	}

	@Benchmark
	public void selectFullUniqueEq(Blackhole bh) {
		bh.consume(engine.execute(fullUniqueEqSql).rows().size());
	}
}
