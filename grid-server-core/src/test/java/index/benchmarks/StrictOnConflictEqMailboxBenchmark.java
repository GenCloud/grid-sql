package index.benchmarks;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicInteger;

import org.genfork.grid.sql.SqlEngine;
import org.genfork.grid.sql.SqlServerRuntime;
import org.openjdk.jmh.annotations.Benchmark;
import org.openjdk.jmh.annotations.BenchmarkMode;
import org.openjdk.jmh.annotations.Fork;
import org.openjdk.jmh.annotations.Level;
import org.openjdk.jmh.annotations.Measurement;
import org.openjdk.jmh.annotations.Mode;
import org.openjdk.jmh.annotations.OutputTimeUnit;
import org.openjdk.jmh.annotations.Scope;
import org.openjdk.jmh.annotations.Setup;
import org.openjdk.jmh.annotations.State;
import org.openjdk.jmh.annotations.TearDown;
import org.openjdk.jmh.annotations.Threads;
import org.openjdk.jmh.annotations.Warmup;
import org.openjdk.jmh.infra.Blackhole;

/**
 * JMH: STRICT ON CONFLICT EQ probe through index mailbox.
 *
 * @author: GenCloud
 * @date: 2026/10
 * @since: 1.3
 */
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.MICROSECONDS)
@Warmup(iterations = 1, time = 1)
@Measurement(iterations = 3, time = 1)
@Fork(1)
@Threads(1)
@State(Scope.Benchmark)
public class StrictOnConflictEqMailboxBenchmark extends AbstractLatencyBenchmark {
	private static final String TABLE = "jmh_conflict_eq";
	private static final int SHARDS = 4;
	private static final String UPSERT_SQL =
			"INSERT INTO " + TABLE + " (event_name, scheduler_name, prev_fire_time) "
					+ "VALUES ('Castle', 'sched-1', TIMESTAMP '2021-01-01 00:00:00') "
					+ "ON CONFLICT (event_name, scheduler_name) DO UPDATE SET "
					+ "prev_fire_time = TIMESTAMP '2021-01-01 00:00:00'";

	private Path dataDir;
	private SqlServerRuntime runtime;
	private SqlEngine engine;
	private final AtomicInteger tick = new AtomicInteger();

	@Setup(Level.Trial)
	public void setup() throws Exception {
		dataDir = Files.createTempDirectory("jmh-conflict-eq");
		runtime = SqlServerRuntime.builder()
				.dataDir(dataDir)
				.shards(SHARDS)
				.durability(false)
				.build();
		engine = runtime.engine();
		engine.execute(
				"CREATE TABLE " + TABLE + " ("
						+ "id INT GENERATED BY DEFAULT AS IDENTITY, "
						+ "event_name VARCHAR NOT NULL, "
						+ "scheduler_name VARCHAR NOT NULL, "
						+ "prev_fire_time TIMESTAMP, "
						+ "PRIMARY KEY (id))");
		engine.execute(
				"CREATE UNIQUE INDEX " + TABLE + "_u ON " + TABLE
						+ " (event_name, scheduler_name)");
		engine.execute(
				"INSERT INTO " + TABLE + " (event_name, scheduler_name, prev_fire_time) "
						+ "VALUES ('Castle', 'sched-1', TIMESTAMP '2020-01-01 00:00:00')");
	}

	@TearDown(Level.Trial)
	public void tearDown() throws Exception {
		if (runtime != null) {
			runtime.close();
			runtime = null;
		}
	}

	@Benchmark
	public void onConflictUpsert(Blackhole bh) {
		bh.consume(engine.execute(UPSERT_SQL).rowsAffected());
		bh.consume(tick.incrementAndGet());
	}
}
