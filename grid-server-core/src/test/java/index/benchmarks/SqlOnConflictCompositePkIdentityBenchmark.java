package index.benchmarks;

import index.sql.SqlBenchHelper;
import org.genfork.grid.sql.SqlEngine;
import org.openjdk.jmh.annotations.Benchmark;
import org.openjdk.jmh.annotations.BenchmarkMode;
import org.openjdk.jmh.annotations.Fork;
import org.openjdk.jmh.annotations.Level;
import org.openjdk.jmh.annotations.Measurement;
import org.openjdk.jmh.annotations.Mode;
import org.openjdk.jmh.annotations.OutputTimeUnit;
import org.openjdk.jmh.annotations.Scope;
import org.openjdk.jmh.annotations.Setup;
import org.openjdk.jmh.annotations.State;
import org.openjdk.jmh.annotations.TearDown;
import org.openjdk.jmh.annotations.Threads;
import org.openjdk.jmh.annotations.Warmup;
import org.openjdk.jmh.infra.Blackhole;

import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicInteger;

/**
 * Hot-path {@code ON CONFLICT} DO UPDATE hit on composite PRIMARY KEY with a separate IDENTITY.
 * <p>
 * Hit must not burn sequence / fail coerce on null {@code id}.
 *
 * @author: GenCloud
 * @date: 2026/10
 * @since: 1.2
 */
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@Warmup(iterations = 1, time = 1)
@Measurement(iterations = 3, time = 1)
@Fork(1)
@Threads(1)
@State(Scope.Benchmark)
public class SqlOnConflictCompositePkIdentityBenchmark extends AbstractLatencyBenchmark {
	private static final int SHARDS = 4;
	private static final int OWNER_ID = 194;
	private static final int SKILL_ID = 39569;
	private static final int SKILL_LEVEL = 1;
	private static final int CLASS_INDEX = 1;
	private static final String TABLE = "timing_onconflict_bench";

	private SqlEngine engine;
	private final AtomicInteger nextRemaining = new AtomicInteger(1_000);

	@Setup(Level.Trial)
	public void setupBenchmark() {
		engine = SqlBenchHelper.createEngine(SHARDS);
		engine.execute(
				"CREATE TABLE " + TABLE + " ("
						+ "id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY, "
						+ "owner_id INT NOT NULL, "
						+ "skill_id INT NOT NULL, "
						+ "skill_level INT NOT NULL, "
						+ "class_index INT NOT NULL, "
						+ "remaining_time INT NOT NULL, "
						+ "PRIMARY KEY (owner_id, skill_id, skill_level, class_index))");
		engine.execute(upsertSql(100));
	}

	@TearDown(Level.Trial)
	public void tearDownBenchmark() {
		if (engine != null && engine.catalog().exists(TABLE)) {
			engine.catalog().dropTable(TABLE);
		}
	}

	@Benchmark
	public void onConflictHitCompositePkSeparateIdentity(Blackhole bh) {
		final int remaining = nextRemaining.getAndIncrement();
		bh.consume(engine.execute(upsertSql(remaining)));
	}

	private static String upsertSql(int remainingTime) {
		return "INSERT INTO " + TABLE + " "
				+ "(owner_id, skill_id, skill_level, class_index, remaining_time) "
				+ "VALUES (" + OWNER_ID + ", " + SKILL_ID + ", " + SKILL_LEVEL + ", "
				+ CLASS_INDEX + ", " + remainingTime + ") "
				+ "ON CONFLICT (owner_id, skill_id, skill_level, class_index) DO UPDATE SET "
				+ "remaining_time = EXCLUDED.remaining_time";
	}
}
