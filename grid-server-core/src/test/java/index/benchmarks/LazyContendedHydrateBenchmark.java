package index.benchmarks;

import org.genfork.grid.sql.SqlEngine;
import org.genfork.grid.sql.SqlServerRuntime;
import org.openjdk.jmh.annotations.Benchmark;
import org.openjdk.jmh.annotations.BenchmarkMode;
import org.openjdk.jmh.annotations.Fork;
import org.openjdk.jmh.annotations.Level;
import org.openjdk.jmh.annotations.Measurement;
import org.openjdk.jmh.annotations.Mode;
import org.openjdk.jmh.annotations.OutputTimeUnit;
import org.openjdk.jmh.annotations.Scope;
import org.openjdk.jmh.annotations.Setup;
import org.openjdk.jmh.annotations.State;
import org.openjdk.jmh.annotations.TearDown;
import org.openjdk.jmh.annotations.Threads;
import org.openjdk.jmh.annotations.Warmup;
import org.openjdk.jmh.infra.Blackhole;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.concurrent.TimeUnit;

/**
 * Contended LAZY first-touch hydrate + AlwaysTrue SELECT vs warm portal path.
 * <p>
 * Calm stamp track: thrpt under {@code @Threads(N)} on cold reopen must not regress vs
 * single-thread baseline of {@link LazySelectHydrateBenchmark}.
 *
 * @author: GenCloud
 * @date: 2026/10
 * @since: 1.3
 */
@BenchmarkMode(Mode.Throughput)
@OutputTimeUnit(TimeUnit.SECONDS)
@Warmup(iterations = 1, time = 1)
@Measurement(iterations = 3, time = 1)
@Fork(1)
@State(Scope.Benchmark)
public class LazyContendedHydrateBenchmark extends AbstractLatencyBenchmark {

	private static final String TABLE = "lazy_contend_jmh";
	private static final String SCHED = "lazy_sched_jmh";
	private static final int SHARDS = 4;
	private static final int SEED_ROWS = Integer.getInteger("grid.lazy.contend.rows", 256);
	private static final String HYDRATE_LAZY = "LAZY";

	private Path dataDir;
	private Path schedDataDir;
	private SqlServerRuntime warmRuntime;
	private SqlEngine warmEngine;

	@Setup(Level.Trial)
	public void seed() throws IOException {
		dataDir = Files.createTempDirectory("lazy-contend-jmh");
		try (SqlServerRuntime writer = openLazy(dataDir)) {
			final SqlEngine engine = writer.engine();
			engine.execute("CREATE TABLE " + TABLE + " (id INT PRIMARY KEY, v VARCHAR)");
			for (int i = 0; i < SEED_ROWS; i++) {
				engine.execute("INSERT INTO " + TABLE + " (id, v) VALUES (" + i + ", 'r" + i + "')");
			}
			writer.replication().dumpDomainSnapshot(TABLE);
		}
		warmRuntime = openLazy(dataDir);
		warmEngine = warmRuntime.engine();
		warmEngine.execute("SELECT id, v FROM " + TABLE);

		schedDataDir = Files.createTempDirectory("lazy-sched-jmh");
		try (SqlServerRuntime writer = openLazy(schedDataDir)) {
			final SqlEngine engine = writer.engine();
			engine.execute("CREATE TABLE " + SCHED + " ("
					+ "id INT GENERATED BY DEFAULT AS IDENTITY, "
					+ "event_name VARCHAR NOT NULL, "
					+ "scheduler_name VARCHAR NOT NULL, "
					+ "PRIMARY KEY (id))");
			engine.execute("CREATE UNIQUE INDEX " + SCHED + "_u ON " + SCHED
					+ " (event_name, scheduler_name)");
			engine.execute("INSERT INTO " + SCHED
					+ " (event_name, scheduler_name) VALUES ('E', 'S')");
			writer.replication().dumpDomainSnapshot(SCHED);
		}
	}

	@TearDown(Level.Trial)
	public void tearDown() {
		if (warmRuntime != null) {
			warmRuntime.close();
			warmRuntime = null;
			warmEngine = null;
		}
	}

	/** Warm AlwaysTrue SELECT (portal-eligible RAM after hydrate). */
	@Benchmark
	@Threads(1)
	public void alwaysTrueSelectWarmPortal(Blackhole bh) {
		bh.consume(warmEngine.execute("SELECT id, v FROM " + TABLE).rows().size());
	}

	/** Contended cold AlwaysTrue after LAZY reopen (sealed-bound → selectCommitted merge). */
	@Benchmark
	@BenchmarkMode(Mode.SingleShotTime)
	@OutputTimeUnit(TimeUnit.MILLISECONDS)
	@Warmup(iterations = 0)
	@Measurement(iterations = 6)
	@Threads(4)
	public void alwaysTrueSelectColdContended(Blackhole bh) {
		try (SqlServerRuntime runtime = openLazy(dataDir)) {
			bh.consume(runtime.engine().execute("SELECT id, v FROM " + TABLE).rows().size());
		}
	}

	/** Contended cold ON CONFLICT first-touch (UNIQUE must be bound before miss path). */
	@Benchmark
	@BenchmarkMode(Mode.SingleShotTime)
	@OutputTimeUnit(TimeUnit.MILLISECONDS)
	@Warmup(iterations = 0)
	@Measurement(iterations = 6)
	@Threads(4)
	public void onConflictColdContended(Blackhole bh) {
		try (SqlServerRuntime runtime = openLazy(schedDataDir)) {
			bh.consume(runtime.engine().execute(
					"INSERT INTO " + SCHED + " (event_name, scheduler_name) VALUES ('E', 'S') "
							+ "ON CONFLICT (event_name, scheduler_name) DO UPDATE SET "
							+ "event_name = 'E', scheduler_name = 'S'").rowsAffected());
		}
	}

	private static SqlServerRuntime openLazy(Path dir) {
		return SqlServerRuntime.builder()
				.dataDir(dir)
				.shards(SHARDS)
				.durability(true)
				.hydrateMode(HYDRATE_LAZY)
				.build();
	}
}
