package index.benchmarks;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.concurrent.TimeUnit;
import java.util.stream.Stream;

import org.genfork.grid.replication.ReplicationCoordinator;
import org.genfork.grid.replication.snapshot.sealed.SealedBPTreeWriter;
import org.genfork.grid.replication.snapshot.sealed.SealedCompositeIndexKey;
import org.genfork.grid.replication.snapshot.sealed.SealedCompositeIndexNames;
import org.genfork.grid.replication.snapshot.sealed.SealedShardPack;
import org.genfork.grid.serial.SqlWireUtil;
import org.genfork.grid.sql.SqlEngine;
import org.genfork.grid.sql.SqlServerRuntime;
import org.openjdk.jmh.annotations.Benchmark;
import org.openjdk.jmh.annotations.BenchmarkMode;
import org.openjdk.jmh.annotations.Fork;
import org.openjdk.jmh.annotations.Level;
import org.openjdk.jmh.annotations.Measurement;
import org.openjdk.jmh.annotations.Mode;
import org.openjdk.jmh.annotations.OutputTimeUnit;
import org.openjdk.jmh.annotations.Scope;
import org.openjdk.jmh.annotations.Setup;
import org.openjdk.jmh.annotations.State;
import org.openjdk.jmh.annotations.TearDown;
import org.openjdk.jmh.annotations.Threads;
import org.openjdk.jmh.annotations.Warmup;
import org.openjdk.jmh.infra.Blackhole;

/**
 * Happy-path STRICT UNIQUE EQ / ON CONFLICT vs cold ghost-{@code .sbpt} heal stamp.
 *
 * @author: GenCloud
 * @date: 2026/10
 * @since: 1.3
 */
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@Warmup(iterations = 1, time = 1)
@Measurement(iterations = 3, time = 1)
@Fork(1)
@Threads(1)
@State(Scope.Benchmark)
public class StrictUniqueEqOnConflictBenchmark extends AbstractLatencyBenchmark {
	private static final int SHARDS = 4;
	private static final int GHOST_PK = 999_999;
	private static final String HYDRATE_LAZY = "LAZY";
	private static final String TABLE = "jmh_uniq_pair_t";
	private static final String UNIQUE_INDEX = TABLE + "_u";
	private static final String K1 = "alpha";
	private static final String K2 = "beta";
	private static final List<String> UNIQUE_COLS = List.of("k1", "k2");
	private static final String EQ_SQL =
			"SELECT id FROM " + TABLE
					+ " WHERE k1 = '" + K1 + "' AND k2 = '" + K2 + "'";
	private static final String UPSERT_SQL =
			"INSERT INTO " + TABLE + " (k1, k2) "
					+ "VALUES ('" + K1 + "', '" + K2 + "') "
					+ "ON CONFLICT (k1, k2) DO UPDATE SET "
					+ "k1 = '" + K1 + "', k2 = '" + K2 + "'";

	private Path dataDir;
	private SqlServerRuntime warmRuntime;
	private SqlEngine warmEngine;

	@Setup(Level.Trial)
	public void seed() throws IOException {
		dataDir = Files.createTempDirectory("jmh-strict-eq");
		try (SqlServerRuntime first = openLazy(dataDir)) {
			final SqlEngine engine = first.engine();
			engine.execute("CREATE TABLE " + TABLE + " ("
					+ "id INT GENERATED BY DEFAULT AS IDENTITY, "
					+ "k1 VARCHAR NOT NULL, "
					+ "k2 VARCHAR NOT NULL, "
					+ "PRIMARY KEY (id))");
			engine.execute("CREATE UNIQUE INDEX " + UNIQUE_INDEX
					+ " ON " + TABLE + " (k1, k2)");
			engine.execute("INSERT INTO " + TABLE + " (k1, k2) VALUES ('"
					+ K1 + "', '" + K2 + "')");
			final ReplicationCoordinator coord = first.replication();
			if (coord != null) {
				coord.dumpDomainSnapshot(TABLE);
			}
		}
		warmRuntime = openLazy(dataDir);
		warmEngine = warmRuntime.engine();
		warmEngine.execute(EQ_SQL);
	}

	@TearDown(Level.Trial)
	public void tearDown() {
		if (warmRuntime != null) {
			warmRuntime.close();
			warmRuntime = null;
			warmEngine = null;
		}
	}

	@Benchmark
	public void uniqueEqHappyPath(Blackhole bh) {
		bh.consume(warmEngine.execute(EQ_SQL).rows().size());
	}

	@Benchmark
	public void onConflictHappyPath(Blackhole bh) {
		bh.consume(warmEngine.execute(UPSERT_SQL).rowsAffected());
	}

	/**
	 * Cold reopen after planting ghost UNIQUE {@code .sbpt} — measures one-shot seal heal.
	 */
	@Benchmark
	@BenchmarkMode(Mode.SingleShotTime)
	@OutputTimeUnit(TimeUnit.MILLISECONDS)
	@Warmup(iterations = 0)
	@Measurement(iterations = 4)
	public void uniqueEqColdGhostHeal(Blackhole bh) throws IOException {
		plantGhostUniqueSbpt(dataDir);
		try (SqlServerRuntime runtime = openLazy(dataDir)) {
			bh.consume(runtime.engine().execute(EQ_SQL).rows().size());
		}
	}

	private static SqlServerRuntime openLazy(Path dir) {
		return SqlServerRuntime.builder()
				.dataDir(dir)
				.shards(SHARDS)
				.durability(true)
				.hydrateMode(HYDRATE_LAZY)
				.build();
	}

	private static void plantGhostUniqueSbpt(Path dataDir) throws IOException {
		final String hex = SealedShardPack.domainHex(TABLE);
		final String sealedName = SealedCompositeIndexNames.of(UNIQUE_COLS);
		final byte[] indexKey = SealedCompositeIndexKey.encode(new byte[][]{
				SqlWireUtil.toGenericArray(K1),
				SqlWireUtil.toGenericArray(K2)
		});
		final byte[] ghostRowKey = SqlWireUtil.toGenericArray(GHOST_PK);
		final List<SealedBPTreeWriter.Entry> entries = List.of(
				new SealedBPTreeWriter.Entry(indexKey, ghostRowKey));
		final String needle = "_idx_" + sealedName + ".sbpt";
		try (Stream<Path> walk = Files.walk(dataDir)) {
			final List<Path> targets = walk
					.filter(p -> {
						final String name = p.getFileName().toString();
						return name.startsWith(hex + "_") && name.endsWith(needle);
					})
					.toList();
			for (Path sbpt : targets) {
				final String name = sbpt.getFileName().toString();
				final int idxStart = name.indexOf("_idx_");
				final int shard = Integer.parseInt(name.substring(hex.length() + 1, idxStart));
				SealedBPTreeWriter.write(sbpt, TABLE, shard, sealedName, entries);
			}
		}
	}
}
