package index.benchmarks;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDate;
import java.time.format.DateTimeFormatter;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicLong;

import org.genfork.grid.replication.ReplicationCoordinator;
import org.genfork.grid.sql.SqlEngine;
import org.genfork.grid.sql.SqlServerRuntime;
import org.junit.jupiter.api.Test;
import org.openjdk.jmh.annotations.Benchmark;
import org.openjdk.jmh.annotations.BenchmarkMode;
import org.openjdk.jmh.annotations.Fork;
import org.openjdk.jmh.annotations.Group;
import org.openjdk.jmh.annotations.GroupThreads;
import org.openjdk.jmh.annotations.Level;
import org.openjdk.jmh.annotations.Measurement;
import org.openjdk.jmh.annotations.Mode;
import org.openjdk.jmh.annotations.OutputTimeUnit;
import org.openjdk.jmh.annotations.Scope;
import org.openjdk.jmh.annotations.Setup;
import org.openjdk.jmh.annotations.State;
import org.openjdk.jmh.annotations.TearDown;
import org.openjdk.jmh.annotations.Warmup;
import org.openjdk.jmh.infra.Blackhole;
import org.openjdk.jmh.results.format.ResultFormatType;
import org.openjdk.jmh.runner.Runner;
import org.openjdk.jmh.runner.options.Options;
import org.openjdk.jmh.runner.options.OptionsBuilder;
import org.openjdk.jmh.runner.options.TimeValue;

/**
 * Contended UNIQUE EQ / ON CONFLICT vs concurrent {@code dumpDomainSnapshot}.
 * <p>
 * Gate: zero sealed-reader-closed under dump pressure. Does not inherit
 * {@link AbstractLatencyBenchmark#runJmh()} {@code threads(1)} — that fights {@link GroupThreads}.
 *
 * @author: GenCloud
 * @date: 2026/10
 * @since: 1.3
 */
@BenchmarkMode(Mode.Throughput)
@OutputTimeUnit(TimeUnit.SECONDS)
@Warmup(iterations = 1, time = 1)
@Measurement(iterations = 3, time = 1)
@Fork(1)
@State(Scope.Benchmark)
public class ContendedUniqueEqVsSealedDumpBenchmark {
	private static final String TABLE = "jmh_dump_eq_sched";
	private static final int SHARDS = 4;
	private static final String HYDRATE_LAZY = "LAZY";
	private static final String EQ_SQL =
			"SELECT id FROM " + TABLE
					+ " WHERE event_name = 'E' AND scheduler_name = 'S'";
	private static final String UPSERT_SQL =
			"INSERT INTO " + TABLE + " (event_name, scheduler_name) "
					+ "VALUES ('E', 'S') "
					+ "ON CONFLICT (event_name, scheduler_name) DO UPDATE SET "
					+ "event_name = 'E', scheduler_name = 'S'";

	private Path dataDir;
	private SqlServerRuntime runtime;
	private SqlEngine engine;
	private ReplicationCoordinator coord;
	private final AtomicLong closedErrors = new AtomicLong();
	private final AtomicLong otherErrors = new AtomicLong();

	@Setup(Level.Trial)
	public void seed() throws IOException {
		dataDir = Files.createTempDirectory("jmh-dump-eq");
		runtime = SqlServerRuntime.builder()
				.dataDir(dataDir)
				.shards(SHARDS)
				.durability(true)
				.hydrateMode(HYDRATE_LAZY)
				.build();
		engine = runtime.engine();
		engine.execute("CREATE TABLE " + TABLE + " ("
				+ "id INT GENERATED BY DEFAULT AS IDENTITY, "
				+ "event_name VARCHAR NOT NULL, "
				+ "scheduler_name VARCHAR NOT NULL, "
				+ "PRIMARY KEY (id))");
		engine.execute("CREATE UNIQUE INDEX " + TABLE + "_u ON " + TABLE
				+ " (event_name, scheduler_name)");
		engine.execute("INSERT INTO " + TABLE
				+ " (event_name, scheduler_name) VALUES ('E', 'S')");
		coord = runtime.replication();
		coord.dumpDomainSnapshot(TABLE);
		engine.execute(EQ_SQL);
	}

	@TearDown(Level.Trial)
	public void tearDown() throws Exception {
		if (runtime != null) {
			runtime.close();
		}
		if (closedErrors.get() > 0L) {
			throw new IllegalStateException(
					"sealed reader closed errors during JMH: " + closedErrors.get());
		}
	}

	@Benchmark
	@Group("dumpEq")
	@GroupThreads(1)
	public void dumpDomain(Blackhole bh) {
		try {
			bh.consume(coord.dumpDomainSnapshot(TABLE));
		} catch (RuntimeException ex) {
			classifyAndSwallow(ex, bh);
		}
	}

	@Benchmark
	@Group("dumpEq")
	@GroupThreads(3)
	public void uniqueEq(Blackhole bh) {
		try {
			bh.consume(engine.execute(EQ_SQL).rows().size());
		} catch (RuntimeException ex) {
			classifyAndSwallow(ex, bh);
		}
	}

	@Benchmark
	@Group("dumpEq")
	@GroupThreads(1)
	public void uniqueUpsert(Blackhole bh) {
		try {
			bh.consume(engine.execute(UPSERT_SQL));
		} catch (RuntimeException ex) {
			classifyAndSwallow(ex, bh);
		}
	}

	/**
	 * Closed-reader is a hard fail (counted + rethrown). Concurrent dump/reindex CME
	 * is counted but swallowed so the closed-reader gate can finish (separate product follow-up).
	 */
	private void classifyAndSwallow(RuntimeException ex, Blackhole bh) {
		if (isClosedReader(ex)) {
			closedErrors.incrementAndGet();
			throw ex;
		}
		otherErrors.incrementAndGet();
		bh.consume(ex.getClass().getName());
	}

	private static boolean isClosedReader(Throwable error) {
		Throwable cursor = error;
		while (cursor != null) {
			final String message = cursor.getMessage();
			if (message != null && message.toLowerCase().contains("closed")) {
				return true;
			}
			cursor = cursor.getCause();
		}
		return false;
	}

	@Test
	public void runJmh() throws Exception {
		final Path resultsDir = Path.of("benchmarks", "results");
		Files.createDirectories(resultsDir);
		String stamp = System.getProperty("jmh.result.stamp");
		if (stamp == null || stamp.isBlank()) {
			stamp = System.getenv("JMH_STAMP");
		}
		if (stamp == null || stamp.isBlank()) {
			stamp = LocalDate.now().format(DateTimeFormatter.ISO_LOCAL_DATE);
		}
		final Path resultFile = resultsDir.resolve(
				stamp + "-throughput-ContendedUniqueEqVsSealedDumpBenchmark.json");
		final Options opt = new OptionsBuilder()
				.include("\\." + getClass().getSimpleName() + "\\.")
				.warmupIterations(1)
				.warmupTime(TimeValue.seconds(1))
				.measurementIterations(3)
				.measurementTime(TimeValue.seconds(1))
				.forks(1)
				.shouldFailOnError(true)
				.resultFormat(ResultFormatType.JSON)
				.result(resultFile.toString())
				.jvmArgs(
						"-server",
						"--add-opens=java.base/java.lang=ALL-UNNAMED",
						"--add-opens=java.base/java.util=ALL-UNNAMED",
						"--add-opens=java.base/java.util.concurrent=ALL-UNNAMED",
						"--add-exports=java.base/jdk.internal.misc=ALL-UNNAMED",
						"--add-modules=jdk.incubator.vector",
						"--enable-preview"
				)
				.build();
		new Runner(opt).run();
		System.out.println("JMH JSON → " + resultFile.toAbsolutePath()
				+ " otherErrors(non-closed)=" + otherErrors.get()
				+ " closedErrors=" + closedErrors.get());
	}
}
