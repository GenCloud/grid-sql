package index.sql;

import java.nio.file.Files;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.Future;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicInteger;

import org.genfork.grid.catalog.TableCatalog;
import org.genfork.grid.sql.SqlEngine;
import org.genfork.grid.sql.SqlResult;
import org.genfork.grid.sql.SqlSession;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * {@code INSERT … ON CONFLICT} on IDENTITY PK + secondary UNIQUE — EventScheduler upsert shape.
 * <p>
 * Concurrent miss probes must not surface {@code duplicate value for unique index}; losers recover
 * to DO UPDATE under the UNIQUE arbiter lock.
 *
 * @author: GenCloud
 * @date: 2026/10
 * @since: 1.2
 */
class SqlOnConflictUniqueIdentityIT {
	private static final int SHARDS = 4;
	private static final int RACE_THREADS = 16;
	private static final int RACE_POOL = 8;
	private static final long AWAIT_SECONDS = 30L;
	private static final String DDL_TABLE =
			"CREATE TABLE event_schedulers ("
					+ "id INT GENERATED BY DEFAULT AS IDENTITY, "
					+ "event_name VARCHAR NOT NULL, "
					+ "scheduler_name VARCHAR NOT NULL, "
					+ "prev_fire_time TIMESTAMP, "
					+ "PRIMARY KEY (id))";
	private static final String DDL_UNIQUE =
			"CREATE UNIQUE INDEX event_schedulers_event_scheduler_uindex "
					+ "ON event_schedulers (event_name, scheduler_name)";
	private static final String UPSERT_SQL =
			"INSERT INTO event_schedulers (event_name, scheduler_name, prev_fire_time) "
					+ "VALUES ('E', 'S', TIMESTAMP '2021-01-01 00:00:00') "
					+ "ON CONFLICT (event_name, scheduler_name) DO UPDATE SET "
					+ "event_name = 'E', scheduler_name = 'S', "
					+ "prev_fire_time = TIMESTAMP '2021-01-01 00:00:00'";

	private SqlEngine engine;

	@BeforeEach
	void setUp() throws Exception {
		engine = new SqlEngine(new TableCatalog(Files.createTempDirectory("on-conflict-uid")), null, SHARDS);
		engine.execute(DDL_TABLE);
		engine.execute(DDL_UNIQUE);
	}

	@Test
	void sequentialUpsertUpdatesSameUniqueRow() {
		engine.execute(
				"INSERT INTO event_schedulers (event_name, scheduler_name, prev_fire_time) "
						+ "VALUES ('E', 'S', TIMESTAMP '2020-01-01 00:00:00')");
		engine.execute(UPSERT_SQL);
		assertEquals(1, engine.execute("SELECT id FROM event_schedulers").rows().size());
		assertEquals(1, engine.execute(
				"SELECT id FROM event_schedulers WHERE event_name = 'E' AND scheduler_name = 'S'")
				.rows().size());
	}

	/**
	 * IT-R3: repeated ON CONFLICT must keep a single IDENTITY id (no ghost PK).
	 */
	@Test
	void onConflictDoesNotAllocateSecondIdentityWhenUniqueExists() {
		engine.execute(
				"INSERT INTO event_schedulers (event_name, scheduler_name, prev_fire_time) "
						+ "VALUES ('E', 'S', TIMESTAMP '2020-01-01 00:00:00')");
		final Object firstId = engine.execute(
				"SELECT id FROM event_schedulers WHERE event_name = 'E' AND scheduler_name = 'S'")
				.rows().getFirst()[0];
		engine.execute(UPSERT_SQL);
		engine.execute(UPSERT_SQL);
		final SqlResult rows = engine.execute(
				"SELECT id FROM event_schedulers WHERE event_name = 'E' AND scheduler_name = 'S'");
		assertEquals(1, rows.rows().size());
		assertEquals(firstId, rows.rows().getFirst()[0]);
		assertEquals(1, engine.execute("SELECT id FROM event_schedulers").rows().size());
	}

	@Test
	void concurrentUpsertSameUniqueDoesNotFail() throws Exception {
		runConcurrentUpserts(false);
	}

	@Test
	void concurrentUpsertSameUniqueInExplicitTxDoesNotFail() throws Exception {
		runConcurrentUpserts(true);
	}

	private void runConcurrentUpserts(boolean explicitTx) throws Exception {
		final ExecutorService pool = Executors.newFixedThreadPool(RACE_POOL);
		final CountDownLatch go = new CountDownLatch(1);
		final AtomicInteger fails = new AtomicInteger();
		final List<Future<?>> futures = new ArrayList<>(RACE_THREADS);
		try {
			for (int i = 0; i < RACE_THREADS; i++) {
				futures.add(pool.submit(() -> {
					try {
						go.await();
						if (explicitTx) {
							final SqlSession session = engine.newSession();
							engine.execute(session, "BEGIN");
							try {
								engine.execute(session, UPSERT_SQL);
								engine.execute(session, "COMMIT");
							} catch (RuntimeException ex) {
								engine.execute(session, "ROLLBACK");
								throw ex;
							}
						} else {
							engine.execute(UPSERT_SQL);
						}
					} catch (Exception ex) {
						fails.incrementAndGet();
					}
				}));
			}
			go.countDown();
			for (Future<?> future : futures) {
				future.get(AWAIT_SECONDS, TimeUnit.SECONDS);
			}
		} finally {
			pool.shutdownNow();
			assertTrue(pool.awaitTermination(AWAIT_SECONDS, TimeUnit.SECONDS));
		}
		assertEquals(0, fails.get(), "concurrent ON CONFLICT must not fail (tx=" + explicitTx + ")");
		assertEquals(1, engine.execute("SELECT id FROM event_schedulers").rows().size());
	}
}
