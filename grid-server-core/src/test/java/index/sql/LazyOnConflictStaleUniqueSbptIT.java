/**
 * Composite STRICT UNIQUE + IDENTITY: {@code INSERT … ON CONFLICT (k1, k2) DO UPDATE}
 * after LAZY reopen when UNIQUE {@code .sbpt} is wrong/empty while {@code .gmap} still
 * holds the live row.
 * <p>
 * Product must UPDATE the existing IDENTITY row — never
 * {@code not unique for strict index} and never a second live PK on the same UNIQUE key.
 *
 * @author: GenCloud
 * @date: 2026/10
 * @since: 1.3
 */
class LazyOnConflictStaleUniqueSbptIT {
	private static final int SHARDS = 4;
	private static final int RACE_THREADS = 8;
	private static final long AWAIT_SECONDS = 60L;
	private static final int GHOST_PK = 999_999;
	private static final String HYDRATE_LAZY = "LAZY";
	private static final String TABLE = "uniq_pair_t";
	private static final String UNIQUE_INDEX = "uniq_pair_t_k1_k2_u";
	private static final String K1 = "alpha";
	private static final String K2 = "beta";
	private static final List<String> UNIQUE_COLS = List.of("k1", "k2");
	private static final String DDL_TABLE =
			"CREATE TABLE " + TABLE + " ("
					+ "id INT GENERATED BY DEFAULT AS IDENTITY, "
					+ "k1 VARCHAR NOT NULL, "
					+ "k2 VARCHAR NOT NULL, "
					+ "ts_col TIMESTAMP, "
					+ "PRIMARY KEY (id))";
	private static final String DDL_UNIQUE =
			"CREATE UNIQUE INDEX " + UNIQUE_INDEX
					+ " ON " + TABLE + " (k1, k2)";
	private static final String SEED_SQL =
			"INSERT INTO " + TABLE + " (k1, k2, ts_col) "
					+ "VALUES ('" + K1 + "', '" + K2 + "', "
					+ "TIMESTAMP '2020-01-01 00:00:00')";
	private static final String UPSERT_SQL =
			"INSERT INTO " + TABLE + " (k1, k2, ts_col) "
					+ "VALUES (?, ?, ?) "
					+ "ON CONFLICT (k1, k2) DO UPDATE SET "
					+ "k1 = ?, k2 = ?, ts_col = ?";
	private static final String SELECT_IDS_SQL =
			"SELECT id FROM " + TABLE
					+ " WHERE k1 = '" + K1 + "' AND k2 = '" + K2 + "'";

	@TempDir(cleanup = CleanupMode.NEVER)
	Path tempDir;

	/**
	 * Authoritative but <em>ghost</em> UNIQUE {@code .sbpt} (non-live PK) → ON CONFLICT must
	 * heal and HIT the seed IDENTITY — never {@code not unique for strict index}.
	 */
	@Test
	void txUpsertAfterGhostUniqueSbptDoesNotSurfaceNotUnique() throws Exception {
		final Path dataDir = tempDir.resolve("lazy-onconflict-ghost-uindex");
		final Object seedId = sealSeedRow(dataDir);
		plantGhostUniqueSbpt(dataDir);

		try (SqlServerRuntime second = openLazy(dataDir)) {
			final SqlEngine engine = second.engine();
			final ReplicationCoordinator coord = second.replication();
			assertNotNull(coord);

			final LocalDateTime fire = LocalDateTime.of(2026, 10, 30, 19, 35, 19, 235_773_200);
			assertDoesNotThrow(() -> upsertInTx(engine, fire),
					"first ON CONFLICT after ghost UNIQUE .sbpt must not fail");
			assertTrue(coord.dumpDomainSnapshot(TABLE) >= 1,
					"bg-style seal must reindex merge map (both live UNIQUE owners)");

			assertDoesNotThrow(() -> upsertInTx(engine, fire.plusSeconds(30L)),
					"second ON CONFLICT must not throw not unique for strict index");

			final SqlResult rows = engine.execute(SELECT_IDS_SQL);
			assertEquals(1, rows.rows().size(),
					"UNIQUE key must keep a single live row (no duplicate IDENTITY)");
			assertEquals(((Number) seedId).intValue(),
					((Number) rows.rows().getFirst()[0]).intValue(),
					"ON CONFLICT must keep seed IDENTITY, not a burned miss-insert id");
			assertEquals(1, engine.execute("SELECT id FROM " + TABLE).rows().size());
		}
	}

	@Test
	void txUpsertAfterEmptyUniqueSbptKeepsSingleIdentity() throws Exception {
		final Path dataDir = tempDir.resolve("lazy-onconflict-empty-uindex");
		final Object seedId = sealSeedRow(dataDir);
		blankUniqueSbpt(dataDir);

		try (SqlServerRuntime second = openLazy(dataDir)) {
			final SqlEngine engine = second.engine();
			final LocalDateTime fire = LocalDateTime.of(2026, 10, 30, 19, 35, 19, 235_773_200);
			upsertInTx(engine, fire);
			upsertInTx(engine, fire.plusSeconds(30L));

			final SqlResult rows = engine.execute(SELECT_IDS_SQL);
			assertEquals(1, rows.rows().size(),
					"UNIQUE key must keep a single live row after empty-.sbpt LAZY ON CONFLICT");
			assertEquals(((Number) seedId).intValue(),
					((Number) rows.rows().getFirst()[0]).intValue(),
					"ON CONFLICT must hit existing IDENTITY (miss→insert burns a new id)");
			assertEquals(1, engine.execute("SELECT id FROM " + TABLE).rows().size());
		}
	}

	@Test
	void concurrentTxUpsertAfterGhostUniqueSbptDoesNotFail() throws Exception {
		final Path dataDir = tempDir.resolve("lazy-onconflict-ghost-uindex-race");
		final Object seedId = sealSeedRow(dataDir);
		plantGhostUniqueSbpt(dataDir);

		try (SqlServerRuntime second = openLazy(dataDir)) {
			final SqlEngine engine = second.engine();
			final ReplicationCoordinator coord = second.replication();
			assertNotNull(coord);
			final ExecutorService pool = Executors.newFixedThreadPool(RACE_THREADS);
			final CountDownLatch go = new CountDownLatch(1);
			final AtomicInteger fails = new AtomicInteger();
			final AtomicReference<String> firstError = new AtomicReference<>();
			final List<Future<?>> futures = new ArrayList<>(RACE_THREADS);
			try {
				for (int i = 0; i < RACE_THREADS; i++) {
					final int tick = i;
					futures.add(pool.submit(() -> {
						try {
							go.await();
							final LocalDateTime fire = LocalDateTime.of(
									2026, 10, 30, 19, 35, 19, 235_773_200 + tick);
							upsertInTx(engine, fire);
						} catch (Exception ex) {
							fails.incrementAndGet();
							firstError.compareAndSet(null, ex.toString());
						}
					}));
				}
				go.countDown();
				for (Future<?> future : futures) {
					future.get(AWAIT_SECONDS, TimeUnit.SECONDS);
				}
			} finally {
				pool.shutdownNow();
				assertTrue(pool.awaitTermination(AWAIT_SECONDS, TimeUnit.SECONDS));
			}

			coord.dumpDomainSnapshot(TABLE);
			try {
				upsertInTx(engine, LocalDateTime.of(2026, 10, 30, 19, 36, 0));
			} catch (Exception ex) {
				fails.incrementAndGet();
				firstError.compareAndSet(null, ex.toString());
			}

			assertEquals(0, fails.get(),
					"TX ON CONFLICT after ghost UNIQUE .sbpt must not fail: " + firstError.get());
			final SqlResult rows = engine.execute(SELECT_IDS_SQL);
			assertEquals(1, rows.rows().size(), "exactly one live row on UNIQUE key");
			assertEquals(((Number) seedId).intValue(),
					((Number) rows.rows().getFirst()[0]).intValue());
			final String err = firstError.get();
			assertFalse(err != null && err.contains("not unique for strict index"),
					"strict collision: " + err);
		}
	}

	private static Object sealSeedRow(Path dataDir) {
		try (SqlServerRuntime first = openLazy(dataDir)) {
			final SqlEngine engine = first.engine();
			engine.execute(DDL_TABLE);
			engine.execute(DDL_UNIQUE);
			engine.execute(SEED_SQL);
			final ReplicationCoordinator coord = first.replication();
			assertNotNull(coord);
			assertTrue(coord.dumpDomainSnapshot(TABLE) >= 1, "seal must persist .gmap");
			final SqlResult seeded = engine.execute(SELECT_IDS_SQL);
			assertEquals(1, seeded.rows().size());
			return seeded.rows().getFirst()[0];
		}
	}

	private static SqlServerRuntime openLazy(Path dataDir) {
		return SqlServerRuntime.builder()
				.dataDir(dataDir)
				.shards(SHARDS)
				.durability(true)
				.hydrateMode(HYDRATE_LAZY)
				.build();
	}

	private static void upsertInTx(SqlEngine engine, LocalDateTime fire) {
		final SqlSession session = engine.newSession();
		engine.execute(session, "BEGIN");
		try {
			final Object[] binds = new Object[]{
					K1, K2, fire,
					K1, K2, fire
			};
			engine.execute(session, UPSERT_SQL, binds);
			engine.execute(session, "COMMIT");
		} catch (RuntimeException ex) {
			engine.execute(session, "ROLLBACK");
			throw ex;
		}
	}

	/**
	 * Authoritative (entryCount &gt; 0) UNIQUE {@code .sbpt} posting a non-live PK — heal skips
	 * incomplete check; conflict EQ soft-misses the real {@code .gmap} row.
	 */
	private static void plantGhostUniqueSbpt(Path dataDir) throws IOException {
		final String hex = SealedShardPack.domainHex(TABLE);
		final String sealedName = SealedCompositeIndexNames.of(UNIQUE_COLS);
		final byte[] indexKey = SealedCompositeIndexKey.encode(new byte[][]{
				SqlWireUtil.toGenericArray(K1),
				SqlWireUtil.toGenericArray(K2)
		});
		final byte[] ghostRowKey = SqlWireUtil.toGenericArray(GHOST_PK);
		final List<SealedBPTreeWriter.Entry> entries = List.of(
				new SealedBPTreeWriter.Entry(indexKey, ghostRowKey));
		rewriteUniqueSbpt(dataDir, hex, sealedName, entries);
	}

	private static void blankUniqueSbpt(Path dataDir) throws IOException {
		final String hex = SealedShardPack.domainHex(TABLE);
		final String sealedName = SealedCompositeIndexNames.of(UNIQUE_COLS);
		rewriteUniqueSbpt(dataDir, hex, sealedName, List.of());
	}

	private static void rewriteUniqueSbpt(
			Path dataDir,
			String hex,
			String sealedName,
			List<SealedBPTreeWriter.Entry> entries
	) throws IOException {
		final String needle = "_idx_" + sealedName + ".sbpt";
		final List<Path> targets;
		try (Stream<Path> walk = Files.walk(dataDir)) {
			targets = walk
					.filter(p -> {
						final String name = p.getFileName().toString();
						return name.startsWith(hex + "_") && name.endsWith(needle);
					})
					.toList();
		}
		assertFalse(targets.isEmpty(), "no UNIQUE .sbpt under " + dataDir);
		for (Path sbpt : targets) {
			final String name = sbpt.getFileName().toString();
			final int shard = parseShard(hex, name);
			SealedBPTreeWriter.write(sbpt, TABLE, shard, sealedName, entries);
		}
	}

	private static int parseShard(String hex, String fileName) {
		final String prefix = hex + "_";
		assertTrue(fileName.startsWith(prefix), fileName);
		final int idxStart = fileName.indexOf("_idx_");
		assertTrue(idxStart > prefix.length(), fileName);
		return Integer.parseInt(fileName.substring(prefix.length(), idxStart));
	}
}
