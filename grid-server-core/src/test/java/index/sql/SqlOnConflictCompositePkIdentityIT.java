package index.sql;

import org.genfork.grid.sql.SqlEngine;
import org.genfork.grid.sql.SqlResult;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;

/**
 * IT-C1: ON CONFLICT on composite PRIMARY KEY with a separate NOT NULL IDENTITY column
 * ({@code player_skills_timing_data} shape) — must not fail with {@code NULL not allowed for id}.
 *
 * @author: GenCloud
 * @date: 2026/10
 * @since: 1.2
 */
class SqlOnConflictCompositePkIdentityIT {
	private static final int SHARDS = 4;

	@Test
	void onConflictCompositePkWithSeparateIdentityDoesNotRejectNullId() {
		final SqlEngine engine = SqlBenchHelper.createEngine(SHARDS);
		engine.execute(
				"CREATE TABLE player_skills_timing_probe ("
						+ "id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY, "
						+ "owner_id INT NOT NULL, "
						+ "skill_id INT NOT NULL, "
						+ "skill_level INT NOT NULL, "
						+ "class_index INT NOT NULL, "
						+ "remaining_time INT NOT NULL, "
						+ "PRIMARY KEY (owner_id, skill_id, skill_level, class_index))");

		engine.execute(
				"INSERT INTO player_skills_timing_probe "
						+ "(owner_id, skill_id, skill_level, class_index, remaining_time) "
						+ "VALUES (194, 39569, 1, 1, 100) "
						+ "ON CONFLICT (owner_id, skill_id, skill_level, class_index) DO UPDATE SET "
						+ "remaining_time = EXCLUDED.remaining_time");

		engine.execute(
				"INSERT INTO player_skills_timing_probe "
						+ "(owner_id, skill_id, skill_level, class_index, remaining_time) "
						+ "VALUES (194, 39569, 1, 1, 3131) "
						+ "ON CONFLICT (owner_id, skill_id, skill_level, class_index) DO UPDATE SET "
						+ "remaining_time = EXCLUDED.remaining_time");

		final SqlResult rows = engine.execute(
				"SELECT id, remaining_time FROM player_skills_timing_probe "
						+ "WHERE owner_id = 194 AND skill_id = 39569 AND skill_level = 1 AND class_index = 1");
		assertEquals(1, rows.rows().size());
		final Object[] row = rows.rows().getFirst();
		assertEquals(1, ((Number) row[0]).intValue());
		assertEquals(3131, ((Number) row[1]).intValue());
	}
}
