package index.sql;

import org.genfork.grid.sql.SqlEngine;
import org.genfork.grid.sql.SqlResult;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * IT-NP1/NP2/NP3: SELECT with non-prefix AND on composite UNIQUE
 * ({@code owner_id AND class_index} while UNIQUE is {@code (owner_id, client_id, class_index)}).
 *
 * @author: GenCloud
 * @date: 2026/10
 * @since: 1.2
 */
class SqlCompositeIndexNonPrefixAndIT {
	private static final int SHARDS = 4;
	private static final String TABLE = "shortcuts_probe";
	private static final String UNIQUE_INDEX = "uq_shortcuts_probe_owner_client_class";
	private static final int OWNER_ID = 194;
	private static final int CLASS_INDEX = 0;
	private static final int ROW_COUNT = 5;

	private SqlEngine engine;

	@BeforeEach
	void setUp() {
		engine = SqlBenchHelper.createEngine(SHARDS);
		engine.execute(
				"CREATE TABLE " + TABLE + " ("
						+ "id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY, "
						+ "owner_id INT NOT NULL, "
						+ "client_id INT NOT NULL, "
						+ "class_index INT NOT NULL, "
						+ "slot INT NOT NULL, "
						+ "PRIMARY KEY (id, owner_id, client_id))");
		engine.execute(
				"CREATE UNIQUE INDEX " + UNIQUE_INDEX + " ON " + TABLE
						+ " (owner_id, client_id, class_index)");
		for (int clientId = 1; clientId <= ROW_COUNT; clientId++) {
			engine.execute(
					"INSERT INTO " + TABLE + " (owner_id, client_id, class_index, slot) VALUES ("
							+ OWNER_ID + ", " + clientId + ", " + CLASS_INDEX + ", " + clientId + ")");
		}
		// Same owner, different class_index — exposes dropped residual (would return 6 instead of 5).
		engine.execute(
				"INSERT INTO " + TABLE + " (owner_id, client_id, class_index, slot) VALUES ("
						+ OWNER_ID + ", 99, 1, 99)");
	}

	@AfterEach
	void tearDown() {
		SqlBenchHelper.closeAllStores(engine);
	}

	@Test
	void selectNonPrefixAndReturnsMatchingRows() {
		final SqlResult rows = engine.execute(
				"SELECT id, class_index FROM " + TABLE
						+ " WHERE owner_id = " + OWNER_ID + " AND class_index = " + CLASS_INDEX);
		assertEquals(ROW_COUNT, rows.rows().size(),
				"IT-NP1: non-prefix AND must filter residual class_index (not owner-only supersets)");
		for (Object[] row : rows.rows()) {
			assertEquals(CLASS_INDEX, ((Number) row[1]).intValue());
		}
	}

	@Test
	void countOwnerOnlyAndFullUniqueEqAgree() {
		final SqlResult count = engine.execute(
				"SELECT COUNT(*) FROM " + TABLE
						+ " WHERE owner_id = " + OWNER_ID + " AND class_index = " + CLASS_INDEX);
		assertEquals(1, count.rows().size());
		assertEquals(ROW_COUNT, ((Number) count.rows().getFirst()[0]).intValue(), "IT-NP2: COUNT");

		final SqlResult ownerOnly = engine.execute(
				"SELECT id FROM " + TABLE + " WHERE owner_id = " + OWNER_ID);
		assertEquals(ROW_COUNT + 1, ownerOnly.rows().size(), "IT-NP2: owner-only includes other class_index");

		final SqlResult fullUnique = engine.execute(
				"SELECT id FROM " + TABLE
						+ " WHERE owner_id = " + OWNER_ID
						+ " AND client_id = 1 AND class_index = " + CLASS_INDEX);
		assertEquals(1, fullUnique.rows().size(), "IT-NP2: full UNIQUE EQ");
	}

	@Test
	void explainNonPrefixAndUsesCompositeUnique() {
		final SqlResult expl = engine.execute(
				"EXPLAIN SELECT id FROM " + TABLE
						+ " WHERE owner_id = " + OWNER_ID + " AND class_index = " + CLASS_INDEX);
		boolean found = false;
		for (Object[] row : expl.rows()) {
			final String detail = String.valueOf(row[2]);
			if (detail.contains("compositeIndex=") && detail.contains(UNIQUE_INDEX)) {
				found = true;
				break;
			}
			if (detail.contains(UNIQUE_INDEX) || detail.contains("owner_id, client_id, class_index")) {
				found = true;
				break;
			}
		}
		assertTrue(found, "IT-NP3: EXPLAIN must show composite UNIQUE access path, got: " + expl.rows());
	}
}
