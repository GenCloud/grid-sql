import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Single-column STRICT UNIQUE EQ faces: ghost {@code .sbpt} while {@code .gmap} holds the live
 * row. Product choke must heal (or fail-closed) — never dual live on the unique key.
 *
 * @author: GenCloud
 * @date: 2026/10
 * @since: 1.3
 */
class StrictUniqueGhostEqHealIT {
	private static final int SHARDS = 4;
	private static final int GHOST_PK = 999_999;
	private static final int LIVE_PK_A = 10;
	private static final int LIVE_PK_B = 20;
	private static final String HYDRATE_LAZY = "LAZY";
	private static final String TABLE = "uniq_name_t";
	private static final String UNIQUE_INDEX = "uniq_name_t_name_u";
	private static final String NAME_COL = "name_key";
	private static final String NAME_VAL = "n1";
	private static final List<String> UNIQUE_COLS = List.of(NAME_COL);
	private static final String DDL_TABLE =
			"CREATE TABLE " + TABLE + " ("
					+ "id INT GENERATED BY DEFAULT AS IDENTITY, "
					+ NAME_COL + " VARCHAR NOT NULL, "
					+ "PRIMARY KEY (id))";
	private static final String DDL_UNIQUE =
			"CREATE UNIQUE INDEX " + UNIQUE_INDEX
					+ " ON " + TABLE + " (" + NAME_COL + ")";
	private static final String SEED_SQL =
			"INSERT INTO " + TABLE + " (" + NAME_COL + ") VALUES ('" + NAME_VAL + "')";
	private static final String SELECT_BY_NAME =
			"SELECT id FROM " + TABLE + " WHERE " + NAME_COL + " = '" + NAME_VAL + "'";
	private static final String SELECT_BY_PK_PREFIX =
			"SELECT id, " + NAME_COL + " FROM " + TABLE + " WHERE id = ";
	private static final String DUAL_COUNT_SQL =
			"SELECT " + NAME_COL + ", COUNT(*) AS c FROM " + TABLE
					+ " GROUP BY " + NAME_COL + " HAVING COUNT(*) > 1";

	@TempDir(cleanup = CleanupMode.NEVER)
	Path tempDir;

	@Test
	void ghostUniqueNameSelectHitsAfterHealKeepsSingleIdentity() throws Exception {
		final Path dataDir = tempDir.resolve("uniq-ghost-select");
		final Object seedId = sealSeedRow(dataDir);
		plantGhostUniqueSbpt(dataDir);

		try (SqlServerRuntime second = openLazy(dataDir)) {
			final SqlEngine engine = second.engine();
			final SqlResult byPk = engine.execute(
					SELECT_BY_PK_PREFIX + ((Number) seedId).intValue());
			assertEquals(1, byPk.rows().size(), "PK / .gmap must still see seed row");
			assertEquals(NAME_VAL, String.valueOf(byPk.rows().getFirst()[1]));

			final SqlResult byName = engine.execute(SELECT_BY_NAME);
			assertEquals(1, byName.rows().size(),
					"STRICT UNIQUE EQ must heal ghost .sbpt and see the live name");
			assertEquals(((Number) seedId).intValue(),
					((Number) byName.rows().getFirst()[0]).intValue());
			assertEquals(0, engine.execute(DUAL_COUNT_SQL).rows().size());
		}
	}

	@Test
	void ghostUniqueNamePlainInsertDoesNotCreateDual() throws Exception {
		final Path dataDir = tempDir.resolve("uniq-ghost-insert");
		final Object seedId = sealSeedRow(dataDir);
		plantGhostUniqueSbpt(dataDir);

		try (SqlServerRuntime second = openLazy(dataDir)) {
			final SqlEngine engine = second.engine();
			assertThrows(NonUniqueValueException.class,
					() -> engine.execute(SEED_SQL),
					"plain INSERT same unique name must STRICT-reject after heal");
			final SqlResult rows = engine.execute(SELECT_BY_NAME);
			assertEquals(1, rows.rows().size());
			assertEquals(((Number) seedId).intValue(),
					((Number) rows.rows().getFirst()[0]).intValue());
			assertEquals(0, engine.execute(DUAL_COUNT_SQL).rows().size());
		}
	}

	@Test
	void onConflictDualLiveRepairsToSingleOwner() throws Exception {
		final Path dataDir = tempDir.resolve("uniq-dual-live-repair");
		Files.createDirectories(dataDir);
		final SqlEngine engine = SqlBenchHelper.createEngine(SHARDS);
		engine.execute(DDL_TABLE);
		engine.execute(DDL_UNIQUE);
		engine.execute("INSERT INTO " + TABLE + " (id, " + NAME_COL + ") VALUES ("
				+ LIVE_PK_A + ", '" + NAME_VAL + "')");
		final TableStore store = SqlBenchHelper.store(engine, TABLE);
		// Keep both map owners: STRICT replace would tombstone A on the second putIndexed.
		clearDisplacedTombstone(store);
		store.putIndexed(LIVE_PK_B, NAME_VAL);
		final Path sbpt = dataDir.resolve("dual.sbpt");
		final byte[] indexKey = SqlWireUtil.toGenericArray(NAME_VAL);
		SealedBPTreeWriter.write(sbpt, TABLE, 0, UNIQUE_COLS.getFirst(), List.of(
				new SealedBPTreeWriter.Entry(indexKey, SqlWireUtil.toGenericArray(LIVE_PK_A)),
				new SealedBPTreeWriter.Entry(indexKey, SqlWireUtil.toGenericArray(LIVE_PK_B))));
		try (SealedBPTreeReader reader = SealedBPTreeReader.open(sbpt)) {
			store.compositeIndex().installSealedFallback(UNIQUE_COLS.getFirst(), reader);
			assertEquals(2, store.lookupEqKeys(UNIQUE_COLS, new byte[][]{indexKey}).size(),
					"precondition: dual live EQ via sealed∪map");

			assertDoesNotThrow(() -> engine.execute(
					"INSERT INTO " + TABLE + " (" + NAME_COL + ") VALUES ('" + NAME_VAL + "') "
							+ "ON CONFLICT (" + NAME_COL + ") DO UPDATE SET "
							+ NAME_COL + " = EXCLUDED." + NAME_COL));
			assertEquals(1, engine.execute(SELECT_BY_NAME).rows().size());
			assertEquals(0, engine.execute(DUAL_COUNT_SQL).rows().size());
		} finally {
			SqlBenchHelper.closeAllStores(engine);
		}
	}

	private static void clearDisplacedTombstone(TableStore store) throws Exception {
		final java.lang.reflect.Field field = TableStore.class.getDeclaredField("indexWorker");
		field.setAccessible(true);
		final GridIndexWorker worker = (GridIndexWorker) field.get(store);
		worker.setDisplacedStrictOwnerTombstone(pk -> {
			// chaos plant only — keep both live map owners
		});
	}

	@Test
	void visibilityEqStableAcrossLazyReopen() throws Exception {
		final Path dataDir = tempDir.resolve("uniq-visibility-reopen");
		final Object seedId = sealSeedRow(dataDir);
		plantGhostUniqueSbpt(dataDir);

		try (SqlServerRuntime second = openLazy(dataDir)) {
			assertEquals(1, second.engine().execute(SELECT_BY_NAME).rows().size());
		}
		try (SqlServerRuntime third = openLazy(dataDir)) {
			final SqlResult rows = third.engine().execute(SELECT_BY_NAME);
			assertEquals(1, rows.rows().size());
			assertEquals(((Number) seedId).intValue(),
					((Number) rows.rows().getFirst()[0]).intValue());
			assertDoesNotThrow(() -> third.engine().execute(
					"INSERT INTO " + TABLE + " (" + NAME_COL + ") VALUES ('" + NAME_VAL + "') "
							+ "ON CONFLICT (" + NAME_COL + ") DO UPDATE SET "
							+ NAME_COL + " = EXCLUDED." + NAME_COL));
			assertEquals(0, third.engine().execute(DUAL_COUNT_SQL).rows().size());
		}
	}

	private static Object sealSeedRow(Path dataDir) {
		try (SqlServerRuntime first = openLazy(dataDir)) {
			final SqlEngine engine = first.engine();
			engine.execute(DDL_TABLE);
			engine.execute(DDL_UNIQUE);
			engine.execute(SEED_SQL);
			final ReplicationCoordinator coord = first.replication();
			assertNotNull(coord);
			assertTrue(coord.dumpDomainSnapshot(TABLE) >= 1);
			final SqlResult seeded = engine.execute(SELECT_BY_NAME);
			assertEquals(1, seeded.rows().size());
			return seeded.rows().getFirst()[0];
		}
	}

	private static SqlServerRuntime openLazy(Path dataDir) {
		return SqlServerRuntime.builder()
				.dataDir(dataDir)
				.shards(SHARDS)
				.durability(true)
				.hydrateMode(HYDRATE_LAZY)
				.build();
	}

	private static void plantGhostUniqueSbpt(Path dataDir) throws IOException {
		final String hex = SealedShardPack.domainHex(TABLE);
		final String sealedName = UNIQUE_COLS.getFirst().toLowerCase(Locale.ROOT);
		final byte[] indexKey = SqlWireUtil.toGenericArray(NAME_VAL);
		final byte[] ghostRowKey = SqlWireUtil.toGenericArray(GHOST_PK);
		final List<SealedBPTreeWriter.Entry> entries = List.of(
				new SealedBPTreeWriter.Entry(indexKey, ghostRowKey));
		rewriteUniqueSbpt(dataDir, hex, sealedName, entries);
	}

	private static void rewriteUniqueSbpt(
			Path dataDir,
			String hex,
			String sealedName,
			List<SealedBPTreeWriter.Entry> entries
	) throws IOException {
		final String needle = "_idx_" + sealedName + ".sbpt";
		final List<Path> targets;
		try (Stream<Path> walk = Files.walk(dataDir)) {
			targets = walk
					.filter(p -> {
						final String name = p.getFileName().toString();
						return name.startsWith(hex + "_") && name.endsWith(needle);
					})
					.toList();
		}
		assertFalse(targets.isEmpty(), "no UNIQUE .sbpt under " + dataDir);
		for (Path sbpt : targets) {
			final String name = sbpt.getFileName().toString();
			final int shard = parseShard(hex, name);
			SealedBPTreeWriter.write(sbpt, TABLE, shard, sealedName, entries);
		}
	}

	private static int parseShard(String hex, String fileName) {
		final String prefix = hex + "_";
		assertTrue(fileName.startsWith(prefix), fileName);
		final int idxStart = fileName.indexOf("_idx_");
		assertTrue(idxStart > prefix.length(), fileName);
		return Integer.parseInt(fileName.substring(prefix.length(), idxStart));
	}
}
