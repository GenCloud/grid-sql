package org.genfork.grid.replication;

import org.genfork.grid.sql.SqlEngine;
import org.genfork.grid.sql.SqlResult;
import org.genfork.grid.sql.SqlServerRuntime;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.CleanupMode;
import org.junit.jupiter.api.io.TempDir;

import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.Future;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicInteger;
import java.util.concurrent.atomic.AtomicReference;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Package-local: concurrent first-touch {@code ON CONFLICT} after LAZY reopen.
 * <p>
 * Flight wait itself is covered by {@link LazyShardHydrateFlightWaitTest} against
 * {@link SealedHydrateService#lazyShardHydrateFlights} (no product test hooks).
 *
 * @author: GenCloud
 * @date: 2026/10
 * @since: 1.3
 */
class LazyShardHydrateSingleFlightOnConflictIT {
	private static final int SHARDS = 4;
	private static final int RACE_THREADS = 8;
	private static final long AWAIT_SECONDS = 60L;
	private static final String HYDRATE_LAZY = "LAZY";
	private static final String TABLE = "event_schedulers";
	private static final String DDL_TABLE =
			"CREATE TABLE " + TABLE + " ("
					+ "id INT GENERATED BY DEFAULT AS IDENTITY, "
					+ "event_name VARCHAR NOT NULL, "
					+ "scheduler_name VARCHAR NOT NULL, "
					+ "prev_fire_time TIMESTAMP, "
					+ "PRIMARY KEY (id))";
	private static final String DDL_UNIQUE =
			"CREATE UNIQUE INDEX event_schedulers_event_scheduler_uindex "
					+ "ON " + TABLE + " (event_name, scheduler_name)";
	private static final String SEED_SQL =
			"INSERT INTO " + TABLE + " (event_name, scheduler_name, prev_fire_time) "
					+ "VALUES ('Castle', 'sched-1', TIMESTAMP '2020-01-01 00:00:00')";
	private static final String UPSERT_SQL =
			"INSERT INTO " + TABLE + " (event_name, scheduler_name, prev_fire_time) "
					+ "VALUES ('Castle', 'sched-1', TIMESTAMP '2021-01-01 00:00:00') "
					+ "ON CONFLICT (event_name, scheduler_name) DO UPDATE SET "
					+ "event_name = 'Castle', scheduler_name = 'sched-1', "
					+ "prev_fire_time = TIMESTAMP '2021-01-01 00:00:00'";

	@TempDir(cleanup = CleanupMode.NEVER)
	Path tempDir;

	@Test
	void concurrentOnConflictAfterLazyReopenKeepsSingleIdentity() throws Exception {
		final Path dataDir = tempDir.resolve("lazy-sf-onconflict");
		try (SqlServerRuntime first = SqlServerRuntime.builder()
				.dataDir(dataDir)
				.shards(SHARDS)
				.durability(true)
				.hydrateMode(HYDRATE_LAZY)
				.build()) {
			final SqlEngine engine = first.engine();
			engine.execute(DDL_TABLE);
			engine.execute(DDL_UNIQUE);
			engine.execute(SEED_SQL);
			final ReplicationCoordinator coord = first.replication();
			assertNotNull(coord);
			assertTrue(coord.dumpDomainSnapshot(TABLE) >= 1);
		}

		try (SqlServerRuntime second = SqlServerRuntime.builder()
				.dataDir(dataDir)
				.shards(SHARDS)
				.durability(true)
				.hydrateMode(HYDRATE_LAZY)
				.build()) {
			assertNotNull(second.replication());
			assertNotNull(second.replication().sealedHydrateService());

			final SqlEngine engine = second.engine();
			final ExecutorService pool = Executors.newFixedThreadPool(RACE_THREADS);
			final CountDownLatch go = new CountDownLatch(1);
			final AtomicInteger fails = new AtomicInteger();
			final AtomicReference<String> firstError = new AtomicReference<>();
			final List<Future<?>> futures = new ArrayList<>(RACE_THREADS);
			try {
				for (int i = 0; i < RACE_THREADS; i++) {
					futures.add(pool.submit(() -> {
						try {
							go.await();
							engine.execute(UPSERT_SQL);
						} catch (Exception ex) {
							fails.incrementAndGet();
							firstError.compareAndSet(null, ex.toString());
						}
					}));
				}
				go.countDown();
				for (Future<?> future : futures) {
					future.get(AWAIT_SECONDS, TimeUnit.SECONDS);
				}
			} finally {
				pool.shutdownNow();
				assertTrue(pool.awaitTermination(AWAIT_SECONDS, TimeUnit.SECONDS));
			}

			assertEquals(0, fails.get(),
					"concurrent ON CONFLICT after LAZY reopen must not fail: " + firstError.get());
			final SqlResult rows = engine.execute(
					"SELECT id FROM " + TABLE
							+ " WHERE event_name = 'Castle' AND scheduler_name = 'sched-1'");
			assertEquals(1, rows.rows().size(), "exactly one live row on UNIQUE key");
			assertEquals(1, engine.execute("SELECT id FROM " + TABLE).rows().size());
		}
	}
}
