package org.genfork.grid.replication.snapshot.sealed;

import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.Future;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicInteger;
import java.util.concurrent.atomic.AtomicReference;

import org.genfork.grid.replication.ReplicationCoordinator;
import org.genfork.grid.sql.SqlEngine;
import org.genfork.grid.sql.SqlResult;
import org.genfork.grid.sql.SqlServerRuntime;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.CleanupMode;
import org.junit.jupiter.api.io.TempDir;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Concurrent sealed dump vs STRICT UNIQUE EQ / ON CONFLICT must not surface closed readers.
 *
 * @author: GenCloud
 * @date: 2026/10
 * @since: 1.3
 */
class SealedDumpConcurrentStrictEqIT {
	private static final int SHARDS = 4;
	private static final int EQ_THREADS = 6;
	private static final int DUMP_ROUNDS = 8;
	private static final long AWAIT_SECONDS = 90L;
	private static final String HYDRATE_LAZY = "LAZY";
	private static final String TABLE = "event_schedulers_dump_eq";
	private static final String DDL_TABLE =
			"CREATE TABLE " + TABLE + " ("
					+ "id INT GENERATED BY DEFAULT AS IDENTITY, "
					+ "event_name VARCHAR NOT NULL, "
					+ "scheduler_name VARCHAR NOT NULL, "
					+ "prev_fire_time TIMESTAMP, "
					+ "PRIMARY KEY (id))";
	private static final String DDL_UNIQUE =
			"CREATE UNIQUE INDEX " + TABLE + "_u "
					+ "ON " + TABLE + " (event_name, scheduler_name)";
	private static final String SEED_SQL =
			"INSERT INTO " + TABLE + " (event_name, scheduler_name, prev_fire_time) "
					+ "VALUES ('Castle', 'sched-1', TIMESTAMP '2020-01-01 00:00:00')";
	private static final String EQ_SQL =
			"SELECT id FROM " + TABLE
					+ " WHERE event_name = 'Castle' AND scheduler_name = 'sched-1'";
	private static final String UPSERT_SQL =
			"INSERT INTO " + TABLE + " (event_name, scheduler_name, prev_fire_time) "
					+ "VALUES ('Castle', 'sched-1', TIMESTAMP '2021-01-01 00:00:00') "
					+ "ON CONFLICT (event_name, scheduler_name) DO UPDATE SET "
					+ "prev_fire_time = TIMESTAMP '2021-01-01 00:00:00'";

	@TempDir(cleanup = CleanupMode.NEVER)
	Path tempDir;

	@Test
	void concurrentDumpAndStrictEqNeverReportsClosedReader() throws Exception {
		final Path dataDir = tempDir.resolve("dump-eq");
		try (SqlServerRuntime runtime = SqlServerRuntime.builder()
				.dataDir(dataDir)
				.shards(SHARDS)
				.durability(true)
				.hydrateMode(HYDRATE_LAZY)
				.build()) {
			final SqlEngine engine = runtime.engine();
			engine.execute(DDL_TABLE);
			engine.execute(DDL_UNIQUE);
			engine.execute(SEED_SQL);
			final ReplicationCoordinator coord = runtime.replication();
			assertNotNull(coord);
			assertTrue(coord.dumpDomainSnapshot(TABLE) >= 1);

			final ExecutorService pool = Executors.newFixedThreadPool(EQ_THREADS + 1);
			final CountDownLatch go = new CountDownLatch(1);
			final AtomicInteger fails = new AtomicInteger();
			final AtomicReference<String> firstError = new AtomicReference<>();
			final List<Future<?>> futures = new ArrayList<>(EQ_THREADS + 1);
			try {
				futures.add(pool.submit(() -> {
					try {
						go.await();
						for (int i = 0; i < DUMP_ROUNDS; i++) {
							coord.dumpDomainSnapshot(TABLE);
						}
					} catch (Exception ex) {
						fails.incrementAndGet();
						firstError.compareAndSet(null, "dump: " + ex);
					}
				}));
				for (int t = 0; t < EQ_THREADS; t++) {
					final int thread = t;
					futures.add(pool.submit(() -> {
						try {
							go.await();
							for (int i = 0; i < DUMP_ROUNDS; i++) {
								if ((thread + i) % 2 == 0) {
									final SqlResult rows = engine.execute(EQ_SQL);
									assertEquals(1, rows.rows().size());
								} else {
									engine.execute(UPSERT_SQL);
								}
							}
						} catch (Exception ex) {
							fails.incrementAndGet();
							firstError.compareAndSet(null, "eq/upsert: " + ex);
						}
					}));
				}
				go.countDown();
				for (Future<?> future : futures) {
					future.get(AWAIT_SECONDS, TimeUnit.SECONDS);
				}
			} finally {
				pool.shutdownNow();
				assertTrue(pool.awaitTermination(AWAIT_SECONDS, TimeUnit.SECONDS));
			}

			assertEquals(0, fails.get(),
					"dump vs STRICT EQ must not fail: " + firstError.get());
			final String err = firstError.get();
			assertFalse(err != null && err.toLowerCase().contains("closed"),
					"must not surface sealed reader closed: " + err);
			assertEquals(1, engine.execute(EQ_SQL).rows().size());
		}
	}
}
