#!/usr/bin/env bash
# No-nemesis latency baseline (algorithm gate). Still runs register+append consistency checkers.
# Default: no --build. JEPSEN_REBUILD=1 or --rebuild rebuilds once; second Ensure-Cluster only recreates volumes.
# Writes benchmarks/jepsen/ARTIFACTS.txt with REGISTER_HISTORY / APPEND_HISTORY for qg-gate.ps1.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"
JEPSEN_DIR="$ROOT/benchmarks/jepsen"
cd "$JEPSEN_DIR"
TIME_LIMIT="${JEPSEN_TIME_LIMIT:-30}"
REBUILD=0
for arg in "$@"; do
  if [[ "$arg" == "--rebuild" || "$arg" == "-Rebuild" ]]; then
    REBUILD=1
  fi
done
if [[ "${JEPSEN_REBUILD:-0}" == "1" ]]; then
  REBUILD=1
fi

ensure_cluster() {
  docker compose down -v --remove-orphans || true
  if [[ "$REBUILD" == "1" ]]; then
    echo "Rebuilding images (once)..."
    export DOCKER_BUILDKIT=1
    docker compose up -d --build --force-recreate n1 n2 n3
    REBUILD=0
  else
    echo "Using existing image..."
    docker compose up -d --force-recreate n1 n2 n3
  fi
  sleep 15
}

# Prefer mvn.cmd on Windows/Git Bash (Unix mvn wrapper + Windows JDK breaks classworlds classpath).
run_mvn() {
  if command -v mvn.cmd >/dev/null 2>&1; then
    mvn.cmd "$@"
  else
    mvn "$@"
  fi
}

install_sql_client() {
  echo "Installing grid-sql-client to local Maven repo..."
  (cd "$ROOT" && run_mvn -B -pl grid-sql-client -am install -DskipTests)
}

ensure_control() {
  docker compose --profile control up -d jepsen
  local ready=0
  local i=0
  while (( i < 90 )); do
    if MSYS_NO_PATHCONV=1 docker compose --profile control exec -T jepsen \
        test -f /tmp/jepsen-control-ready >/dev/null 2>&1; then
      ready=1
      break
    fi
    sleep 2
    i=$((i + 1))
  done
  if [[ "$ready" != "1" ]]; then
    echo "ERROR: jepsen control did not become ready (lein bootstrap)" >&2
    return 1
  fi
  return 0
}

run_workload() {
  local workload="$1"
  ensure_control
  MSYS_NO_PATHCONV=1 docker compose --profile control exec -T \
    -e JAVA_HOME=/opt/java/openjdk \
    -e JAVA_CMD=/opt/java/openjdk/bin/java \
    jepsen sh -c "set -e; export PATH=/opt/java/openjdk/bin:/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin; cd /jepsen/jamoa; export JEPSEN_NODES=n1,n2,n3 JEPSEN_HTTP_PORTS=7777,7778,7779 JEPSEN_SQL_PORTS=15432,15433,15434 JEPSEN_SCRIPTS=/jepsen/scripts JEPSEN_USE_LOCALHOST=0; lein run -m jamoa-jepsen.core test --workload ${workload} --time-limit ${TIME_LIMIT} --no-nemesis"
}

# Newest history.edn under store/<test-name>/<timestamp>/ where test-name contains needle.
# Layout: store/jamoa-orchid-register-nochao/20260925T.../history.edn
find_history() {
  local needle="$1"
  local store="$JEPSEN_DIR/clojure/store"
  if [[ ! -d "$store" ]]; then
    return 1
  fi
  local hit
  # Prefer *-nochao* runs for this workload, then any matching orchid-<needle> path.
  hit="$(find "$store" -type f -name history.edn 2>/dev/null \
    | while read -r f; do
        case "$f" in
          *"jamoa-orchid-${needle}-nochao"*)
            printf '2\t%s\t%s\n' "$(stat -c '%Y' "$f" 2>/dev/null || stat -f '%m' "$f")" "$f"
            ;;
          *"jamoa-orchid-${needle}/"*|*"jamoa-orchid-${needle}\\"*)
            printf '1\t%s\t%s\n' "$(stat -c '%Y' "$f" 2>/dev/null || stat -f '%m' "$f")" "$f"
            ;;
        esac
      done \
    | sort -nr \
    | head -1 \
    | cut -f3-)"
  if [[ -n "$hit" ]]; then
    printf '%s\n' "$hit"
    return 0
  fi
  return 1
}

write_artifacts() {
  local reg app artifacts
  artifacts="$JEPSEN_DIR/ARTIFACTS.txt"
  reg="$(find_history register || true)"
  app="$(find_history append || true)"
  # Host-native paths for qg-gate.ps1 (cygpath on Git Bash/Windows; identity on Linux CI).
  if command -v cygpath >/dev/null 2>&1; then
    [[ -n "$reg" ]] && reg="$(cygpath -m "$reg")"
    [[ -n "$app" ]] && app="$(cygpath -m "$app")"
  fi
  {
    echo "# Generated by run-jepsen-nochao.sh - source for qg-gate"
    echo "REGISTER_HISTORY=${reg}"
    echo "APPEND_HISTORY=${app}"
  } > "$artifacts"
  echo "Wrote $artifacts"
  echo "REGISTER_HISTORY=${reg:-<missing>}"
  echo "APPEND_HISTORY=${app:-<missing>}"
  if [[ -z "$reg" || -z "$app" ]]; then
    echo "WARN: one or both history.edn paths missing under clojure/store" >&2
    return 1
  fi
  return 0
}

install_sql_client
ensure_cluster
echo "=== no-chaos register ==="
run_workload register
ensure_cluster
echo "=== no-chaos append ==="
run_workload append
echo "no-chaos done; collect latency from store/*/history.edn"
write_artifacts || true